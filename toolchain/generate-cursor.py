#!/usr/bin/env python3
"""Prealign the original doubled cursors to avoid per-pixel work on an 8086."""
from pathlib import Path
outlines=((0x80,0xc0,0xe0,0xf0,0xf8,0xfc,0xfe,0xff,0xf8,0xd8,0x8c,0x0c),
          (0xc0,0xe0,0xe0,0xe0,0xfc,0xfe,0xff,0xff,0xff,0x7e,0x3e,0x3c))
interiors=((0,0,0x40,0x60,0x70,0x78,0x7c,0x60,0x60,0x40,0,0),
           (0,0x40,0x40,0x40,0x40,0x54,0x54,0x7e,0x3e,0x3c,0x1c,0))
def aligned(bits,shift):
    doubled=sum(3<<(2*i) for i in range(8) if bits&(1<<i))
    word=(doubled<<8)>>shift
    return [(word>>n)&255 for n in (16,8,0)]
lines=['/* Generated by toolchain/generate-cursor.py. Original ELKSWeb artwork.',
       ' * SPDX-License-Identifier: GPL-2.0-or-later */',
       'static const unsigned char cursor_bitmap[2][8][12][6] = {']
for shape in range(2):
    lines.append(' {')
    for shift in range(8):
        lines.append('  {')
        for row in range(12):
            data=aligned(outlines[shape][row],shift)+aligned(interiors[shape][row],shift)
            lines.append('   {'+','.join('0x%02x'%v for v in data)+'},')
        lines.append('  },')
    lines.append(' },')
lines.append('};')
(Path(__file__).resolve().parents[1]/'platform/cursor_bitmap.h').write_text('\n'.join(lines)+'\n')
