#!/usr/bin/env python3
"""Pack unscaled public-domain X.Org fixed ASCII glyphs for ELKSWeb."""
from pathlib import Path
HERE=Path(__file__).resolve().parent
FACES=('6x10.bdf','6x13.bdf','6x13B.bdf','7x14.bdf','7x14B.bdf')
def read_bdf(path):
    lines=Path(path).read_text().splitlines(); glyphs={}; code=None; width=height=None
    for i,line in enumerate(lines):
        if line.startswith('FONTBOUNDINGBOX '):width,height,_,_=map(int,line.split()[1:])
        if line.startswith('ENCODING '):code=int(line.split()[1])
        if line=='BITMAP' and code is not None and 32<=code<127:
            j=i+1;rows=[]
            while lines[j]!='ENDCHAR': rows.append(int(lines[j],16));j+=1
            assert len(rows)==height,(path,code,len(rows),height)
            glyphs[code]=rows
    assert set(glyphs)==set(range(32,127))
    return width,height,glyphs

def generate():
    out=['/* Generated by generate_fixed.py; public-domain X.Org glyphs. See FIXED-COPYING. */']
    for n,name in enumerate(FACES):
        w,h,glyphs=read_bdf(HERE/name)
        out.append('static const unsigned char face%d[95][%d] = {'%(n,h))
        for c in range(32,127):out.append(' {'+','.join('0x%02x'%r for r in glyphs[c])+'},')
        out.append('};')
    out.append('static const unsigned char *const faces[5] = {face0[0],face1[0],face2[0],face3[0],face4[0]};')
    return '\n'.join(out)+'\n'
if __name__=='__main__':(HERE/'fixed_data.h').write_text(generate())
