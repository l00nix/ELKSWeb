#!/usr/bin/env python3
"""Generate deterministic ASCII font tables from independently sourced X.Org BDF."""
from pathlib import Path

HERE=Path(__file__).resolve().parent


def read_font(path):
    glyphs={}
    current=None
    bitmap=False
    for line in path.read_text().splitlines():
        parts=line.split()
        if not parts:continue
        if parts[0]=='STARTCHAR':current={};bitmap=False
        elif parts[0]=='ENCODING':current['code']=int(parts[1])
        elif parts[0]=='DWIDTH':current['advance']=int(parts[1])
        elif parts[0]=='BBX':current['box']=list(map(int,parts[1:]));current['rows']=[]
        elif parts[0]=='BITMAP':bitmap=True
        elif parts[0]=='ENDCHAR':glyphs[current['code']]=current;bitmap=False
        elif bitmap:current['rows'].append(int(parts[0],16))
    result=[]
    for code in range(32,127):
        glyph=glyphs[code]
        width,height,xoff,yoff=glyph['box']
        if width>8 or height!=len(glyph['rows']):raise ValueError('Unsupported glyph dimensions')
        rows=[0]*10
        top=8-height-yoff
        if top<0 or top+height>10:raise ValueError('Glyph exceeds 8+2 pixel line box')
        rows[top:top+height]=glyph['rows']
        result.append((glyph['advance'],xoff,rows))
    return result


def generate():
    out=['/* Generated by font/generate.py. Do not edit tables by hand.',
         ' * Copyright 1984-1989, 1994 Adobe Systems Incorporated.',
         ' * Copyright 1988, 1994 Digital Equipment Corporation.',
         ' * Permission to use/copy/modify/distribute/sell under font/COPYING.',
         ' * The source BDF files are from X.Org font-adobe-75dpi 1.0.4.',
         ' */','#include "font.h"','#include "../platform/elks_platform.h"','',
         'struct ew_glyph { unsigned char advance; signed char bearing; unsigned char rows[10]; };']
    for name,source in [('regular','helvR08.bdf'),('bold','helvB08.bdf')]:
        out.append('static const struct ew_glyph '+name+'[95] = {')
        for advance,bearing,rows in read_font(HERE/source):
            out.append('    {%d,%d,{%s}},'%(advance,bearing,','.join('0x%02x'%v for v in rows)))
        out.append('};')
    out.append(r'''
static const struct ew_glyph *glyph_for(unsigned char c, int is_bold)
{
    if (c == 160) c = ' ';
    if (c < 32 || c > 126) c = '?';
    return (is_bold ? bold : regular) + c - 32;
}

int ew_font_char_width(unsigned char c, int is_bold)
{
    return glyph_for(c, is_bold)->advance * EW_FONT_X_SCALE;
}

int ew_font_height(int is_bold)
{
    (void)is_bold;
    return 10;
}

int ew_font_width(const char EW_FONT_FAR *text, unsigned count, int is_bold)
{
    unsigned width = 0;
    while (count-- && *text) {
        unsigned advance = glyph_for((unsigned char)*text++, is_bold)->advance * EW_FONT_X_SCALE;
        if (width > 32767U - advance) return 32767;
        width += advance;
    }
    return (int)width;
}

static void draw_glyph(int x, int y, unsigned char c, int fg, int bg, int is_bold, int italic)
{
    const struct ew_glyph *glyph = glyph_for(c, is_bold);
    int row, column, skew;
    unsigned char bits;
    if (x < -8 * EW_FONT_X_SCALE || x >= EW_SCREEN_WIDTH || y <= -10 || y >= EW_SCREEN_HEIGHT)
        return;
    if (bg >= 0) ew_fillrect(x, y, glyph->advance * EW_FONT_X_SCALE, 10, bg);
    for (row = 0; row < 10; ++row) {
        skew = italic ? (9 - row) / 4 : 0;
        bits = glyph->rows[row];
        if (!bits) continue;
        for (column = 0; column < 8; ++column)
            if (bits & (0x80U >> column))
                ew_fillrect(x + (glyph->bearing + column) * EW_FONT_X_SCALE + skew,
                            y + row, EW_FONT_X_SCALE, 1, fg);
    }
}

void ew_font_draw(int x, int y, unsigned char c, int fg, int bg, int is_bold)
{
    draw_glyph(x, y, c, fg, bg, is_bold, 0);
}

void ew_font_draw_italic(int x, int y, unsigned char c, int fg, int bg, int is_bold)
{
    draw_glyph(x, y, c, fg, bg, is_bold, 1);
}
''')
    return '\n'.join(out)


if __name__=='__main__':(HERE/'font.c').write_text(generate())
